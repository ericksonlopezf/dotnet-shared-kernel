    [Fact]
    public void GetStrongIdTypeInfo_WhenDeclaredSymbolIsNull_ReturnsNull()
    {
        var method = typeof(DapperRegistrationGenerator).GetMethod("GetStrongIdTypeInfo", BindingFlags.NonPublic | BindingFlags.Static);
        method.Should().NotBeNull();

        var tree = CSharpSyntaxTree.ParseText("public class Sample { }");
        var node = tree.GetRoot().DescendantNodes().OfType<TypeDeclarationSyntax>().First();

        var semanticModel = Substitute.For<SemanticModel>();
        semanticModel.GetDeclaredSymbol(Arg.Any<SyntaxNode>(), Arg.Any<System.Threading.CancellationToken>()).Returns((ISymbol?)null);

        var contextType = typeof(GeneratorSyntaxContext);
        var ctor = contextType.GetConstructors(BindingFlags.NonPublic | BindingFlags.Instance).First();
        var context = ctor.Invoke(new object[] { node, new Lazy<SemanticModel>(() => semanticModel), null! });

        var result = method!.Invoke(null, new object[] { context, System.Threading.CancellationToken.None });
        result.Should().BeNull();
    }

    [Fact]
    public void DapperStrongIdItem_EqualityAndHashCode_WorkCorrectly()
    {
        var itemType = typeof(DapperRegistrationGenerator).Assembly
            .GetType("EricksonLopez.SharedKernel.SourceGenerators.DapperRegistrationGenerator+DapperStrongIdItem");

        itemType.Should().NotBeNull();

        var item1 = Activator.CreateInstance(itemType!, "global::App.Id1", "global::System.Guid");
        var item2 = Activator.CreateInstance(itemType!, "global::App.Id1", "global::System.Guid");
        var item3 = Activator.CreateInstance(itemType!, "global::App.Id2", "int");
        var item4 = Activator.CreateInstance(itemType!, "global::App.Id1", "int");

        item1.Should().Be(item2);
        item1.Should().NotBe(item3);
        item1.Should().NotBe(item4);
        item1.Should().NotBe(null);
        item1.Should().NotBe(new object());
        item1!.GetHashCode().Should().Be(item2!.GetHashCode());
    }

    private static GeneratorDriverRunResult RunGeneratorDriver<TGenerator>(string source)
        where TGenerator : IIncrementalGenerator, new()
    {
        var syntaxTree = CSharpSyntaxTree.ParseText(source);
        var references = new MetadataReference[]
        {
            MetadataReference.CreateFromFile(typeof(object).Assembly.Location),
            MetadataReference.CreateFromFile(typeof(Attribute).Assembly.Location),
            MetadataReference.CreateFromFile(typeof(IStrongId<,>).Assembly.Location),
        };

        var compilation = CSharpCompilation.Create(
            "TestCompilation",
            new[] { syntaxTree },
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        var generator = new TGenerator();
        GeneratorDriver driver = CSharpGeneratorDriver.Create(generator);
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out _, out var diagnostics);
        diagnostics.Should().NotContain(d => d.Severity == DiagnosticSeverity.Error);

        return driver.GetRunResult();
    }

    private static GeneratorDriverRunResult RunGeneratorDriverWithSharedKernel<TGenerator>(string source)
        where TGenerator : IIncrementalGenerator, new()
    {
        const string attributeSource = @"
namespace EricksonLopez.SharedKernel
{
    [System.AttributeUsage(System.AttributeTargets.Struct | System.AttributeTargets.Class)]
    public sealed class StrongIdAttribute : System.Attribute
    {
        public System.Type ValueType { get; }
        public StrongIdAttribute(System.Type valueType) => ValueType = valueType;
    }
}
";
        var syntaxTree = CSharpSyntaxTree.ParseText(source);
        var attrTree = CSharpSyntaxTree.ParseText(attributeSource);
        var references = new MetadataReference[]
        {
            MetadataReference.CreateFromFile(typeof(object).Assembly.Location),
            MetadataReference.CreateFromFile(typeof(Attribute).Assembly.Location),
            MetadataReference.CreateFromFile(typeof(IStrongId<,>).Assembly.Location),
        };

        var compilation = CSharpCompilation.Create(
            "TestCompilation",
            new[] { syntaxTree, attrTree },
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        var generator = new TGenerator();
        GeneratorDriver driver = CSharpGeneratorDriver.Create(generator);
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out _, out var diagnostics);
        diagnostics.Should().NotContain(d => d.Severity == DiagnosticSeverity.Error);

        return driver.GetRunResult();
    }
