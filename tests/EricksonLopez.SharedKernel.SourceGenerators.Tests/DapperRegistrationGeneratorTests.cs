    private static string Normalize(string s) => RoslynTestSyntaxHelper.Normalize(s);

    [Fact]
    public void Generator_RegistersAttributeSource_DuringPostInitialization()
    {
        var runResult = RunGeneratorDriver<DapperRegistrationGenerator>("// empty");

        var attributeTree = runResult.GeneratedTrees.FirstOrDefault(t => t.FilePath.EndsWith("GenerateDapperStrongIdRegistrationsAttribute.g.cs", StringComparison.Ordinal));
        attributeTree.Should().NotBeNull();
        var content = Normalize(attributeTree!.ToString());

        const string expectedAttributeSource = @"// <auto-generated/>
#nullable enable
namespace EricksonLopez.SharedKernel.Dapper
{
    /// <summary>
    /// Instructs the source generator to generate compile-time Native AOT Dapper type handler registrations for all StrongIds in this compilation.
    /// </summary>
    [global::System.AttributeUsage(global::System.AttributeTargets.Assembly | global::System.AttributeTargets.Class, Inherited = false, AllowMultiple = false)]
    internal sealed class GenerateDapperStrongIdRegistrationsAttribute : global::System.Attribute
    {
    }
}";

        content.Should().Be(Normalize(expectedAttributeSource));
    }

    [Fact]
    public void Generator_DiscoversAllStrongIdVariations_GeneratesExactSortedAotRegistrations()
    {
        const string source = @"
using System;
using EricksonLopez.DomainPrimitives;
using EricksonLopez.SharedKernel;

namespace SampleApp;

[StrongId<string>]
public readonly record struct CodeId(string Value);

public readonly record struct DeptId(int Value) : IStrongId<DeptId, int>;
public readonly record struct OrderId(Guid Value) : IStrongId<OrderId, Guid>;
public readonly record struct CustomerId(Guid Value) : IStrongId<CustomerId, Guid>;

public abstract class AbstractId : IStrongId<AbstractId, Guid>;
public class PlainClass { public int Id { get; set; } }
";

        var runResult = RunGeneratorDriver<DapperRegistrationGenerator>(source);

        var regTree = runResult.GeneratedTrees.FirstOrDefault(t => t.FilePath.EndsWith("GeneratedDapperStrongIdRegistryExtensions.g.cs", StringComparison.Ordinal));
        regTree.Should().NotBeNull();
        var output = Normalize(regTree!.ToString());

        const string expectedOutput = @"// <auto-generated/>
#nullable enable

namespace EricksonLopez.SharedKernel.Dapper
{
    /// <summary>
    /// Compile-time generated Native AOT &amp; Trimming safe Dapper StrongId registrations.
    /// </summary>
    public static class GeneratedDapperStrongIdRegistryExtensions
    {
        /// <summary>
        /// Registers all discovered Strongly-Typed IDs with Dapper's SqlMapper without runtime reflection.
        /// </summary>
        public static void RegisterAllGeneratedStrongIds()
        {
            global::EricksonLopez.SharedKernel.Dapper.DapperStrongIdRegistry.Register<global::SampleApp.CodeId, string>();
            global::EricksonLopez.SharedKernel.Dapper.DapperStrongIdRegistry.Register<global::SampleApp.CustomerId, global::System.Guid>();
            global::EricksonLopez.SharedKernel.Dapper.DapperStrongIdRegistry.Register<global::SampleApp.DeptId, int>();
            global::EricksonLopez.SharedKernel.Dapper.DapperStrongIdRegistry.Register<global::SampleApp.OrderId, global::System.Guid>();
        }
    }
}";

        output.Should().Be(Normalize(expectedOutput));
    }

