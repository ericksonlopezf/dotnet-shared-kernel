    #region PERF-01: PropertyMetadata Zero-Boxing Accessors

    private sealed class EntityForPerf
    {
        public int Id { get; set; }
    }

    [Fact]
    public void PropertyMetadata_GetValue_WithStronglyTypedGetter_IncursZeroAllocations()
    {
        var entity = new EntityForPerf { Id = 42 };
        Func<EntityForPerf, int> typedGetter = e => e.Id;

        var prop = new EricksonLopez.SharedKernel.Persistence.PropertyMetadata(
            ClrName: nameof(EntityForPerf.Id),
            ClrType: typeof(int),
            ColumnName: "id",
            DatabaseType: "integer",
            IsKey: true,
            IsNullable: false,
            IsAuditColumn: false,
            IsSoftDeleteColumn: false,
            IsTenantColumn: false,
            IsConcurrencyToken: false,
            Getter: obj => ((EntityForPerf)obj).Id,
            Setter: null)
        {
            StronglyTypedGetter = typedGetter
        };

        // Warm up JIT
        _ = prop.GetValue<EntityForPerf, int>(entity);

        long bytesBefore = GC.GetAllocatedBytesForCurrentThread();
        for (int i = 0; i < 10_000; i++)
        {
            var val = prop.GetValue<EntityForPerf, int>(entity);
            _ = val + i;
        }
        long bytesAfter = GC.GetAllocatedBytesForCurrentThread();
        long totalAllocated = bytesAfter - bytesBefore;

        totalAllocated.Should().Be(0, because: "Strongly-typed GetValue on PropertyMetadata must execute with zero heap boxing allocations.");
    }

