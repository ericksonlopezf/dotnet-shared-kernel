    #region FND-01: DomainEvents Tamper Resistance

    [Fact]
    public void AggregateRoot_DomainEvents_CannotBeCastToMutableIList_ThwartingTampering()
    {
        // Arrange
        var aggregate = new OrderAggregate(Guid.NewGuid());
        aggregate.EmitEvent(new TestDomainEvent("Original Event"));

        // Act
        var events = aggregate.DomainEvents;

        // Assert: ReadOnlyDomainEventList does NOT implement IList<IDomainEvent> or IList
        (events is IList<IDomainEvent>).Should().BeFalse(
            because: "DomainEvents must return a truly immutable list that cannot be downcast to IList<IDomainEvent>");

        (events is System.Collections.IList).Should().BeFalse(
            because: "DomainEvents must not implement non-generic IList");

        // Action cast to IList<IDomainEvent> throws InvalidCastException
        Action castAction = () => { var _ = (IList<IDomainEvent>)events; };
        castAction.Should().Throw<InvalidCastException>();

        // Drained events are unaltered
        var drained = aggregate.DrainDomainEvents();
        drained.Should().HaveCount(1);
        drained[0].Should().BeOfType<TestDomainEvent>();
    }

    [Fact]
    public void AggregateRoot_DrainDomainEvents_CannotBeCastToMutableIList()
    {
        // Arrange
        var aggregate = new OrderAggregate(Guid.NewGuid());
        aggregate.EmitEvent(new TestDomainEvent("Drained Event"));

        // Act
        var drained = aggregate.DrainDomainEvents();

        // Assert
        (drained is IList<IDomainEvent>).Should().BeFalse();
        Action castAction = () => { var _ = (IList<IDomainEvent>)drained; };
        castAction.Should().Throw<InvalidCastException>();
    }

