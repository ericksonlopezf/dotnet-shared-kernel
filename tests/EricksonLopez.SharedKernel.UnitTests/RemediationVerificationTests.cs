    #region FND-02: Class-Based Strong ID Null Safety

    // Simulated non-record class strong ID as generated by StrongIdGenerator
    public class CustomerId : IEquatable<CustomerId>
    {
        public Guid Value { get; init; }

        public CustomerId(Guid value) => Value = value;

        public bool Equals(CustomerId? other) => other is not null && Value.Equals(other.Value);

        public override bool Equals(object? obj) => obj is CustomerId other && Equals(other);

        public override int GetHashCode() => Value.GetHashCode();

        public static bool operator ==(CustomerId? left, CustomerId? right) =>
            ReferenceEquals(left, right) || (left is not null && left.Equals(right));

        public static bool operator !=(CustomerId? left, CustomerId? right) => !(left == right);
    }

    [Fact]
    public void ClassBasedStrongId_EqualsNull_ReturnsFalse_WithoutThrowing()
    {
        var id = new CustomerId(Guid.NewGuid());

        bool equalsStrongNull = id.Equals((CustomerId?)null);
        equalsStrongNull.Should().BeFalse(because: "Equals(null) must return false per .NET contracts");

        object? nullObj = null;
        bool equalsObjectNull = id.Equals(nullObj);
        equalsObjectNull.Should().BeFalse();
    }

    [Fact]
    public void ClassBasedStrongId_OperatorEqualityWithNull_ReturnsFalse_WithoutThrowing()
    {
        CustomerId? nullId = null;
        var validId = new CustomerId(Guid.NewGuid());

        bool nullEqualsValid = nullId == validId;
        nullEqualsValid.Should().BeFalse();

        bool validEqualsNull = validId == nullId;
        validEqualsNull.Should().BeFalse();

        bool nullNotEqualsValid = nullId != validId;
        nullNotEqualsValid.Should().BeTrue();

        bool validNotEqualsNull = validId != nullId;
        validNotEqualsNull.Should().BeTrue();
    }

