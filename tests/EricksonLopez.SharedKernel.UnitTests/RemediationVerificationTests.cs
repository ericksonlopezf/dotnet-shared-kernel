    #region FND-SK-009: DomainEvent Identity Equality

    [Fact]
    public void DomainEventIdentityEqualityComparer_ComparesStrictlyById()
    {
        var id = EventId.New();
        var evt1 = new ExplicitEvent(id, DateTimeOffset.UtcNow, "Payload A");
        var evt2 = new ExplicitEvent(id, DateTimeOffset.UtcNow.AddMinutes(5), "Payload B");

        // Object equality (record memberwise comparison)
        (evt1 == evt2).Should().BeFalse(because: "Record equality compares all members.");

        // Identity equality comparison
        DomainEventIdentityEqualityComparer.Instance.Equals(evt1, evt2).Should().BeTrue(
            because: "DomainEventIdentityEqualityComparer must evaluate equality based strictly on EventId per FND-SK-009.");
        DomainEventIdentityEqualityComparer.Instance.GetHashCode(evt1).Should().Be(
            DomainEventIdentityEqualityComparer.Instance.GetHashCode(evt2));
    }

    private sealed record ExplicitEvent : DomainEvent
    {
        public string Payload { get; }

        public ExplicitEvent(EventId id, DateTimeOffset occurredAt, string payload)
            : base(id, occurredAt)
        {
            Payload = payload;
        }
    }

