    #region FND-SK-005: IHasDomainEvents Contract & Requeue

    private sealed class CustomHasDomainEvents : IHasDomainEvents
    {
        private readonly List<IDomainEvent> _events = [];

        public IReadOnlyList<IDomainEvent> DomainEvents => _events;

        public void Add(IDomainEvent evt) => _events.Add(evt);

        public IReadOnlyList<IDomainEvent> DrainDomainEvents()
        {
            var copy = _events.ToArray();
            _events.Clear();
            return copy;
        }

        public void RequeueDomainEvents(IEnumerable<IDomainEvent> events)
        {
            _events.InsertRange(0, events);
        }
    }

    [Fact]
    public void IHasDomainEvents_DomainEvents_IsAbstractProperty()
    {
        var prop = typeof(IHasDomainEvents).GetProperty(nameof(IHasDomainEvents.DomainEvents));
        prop.Should().NotBeNull();
        prop!.GetMethod.Should().NotBeNull();
        prop.GetMethod!.IsAbstract.Should().BeTrue(because: "DomainEvents must be an abstract interface property per FND-SK-005.");
    }

    [Fact]
    public void AggregateRoot_RequeueDomainEvents_RestoresEventsInCorrectOrder()
    {
        var aggregate = new OrderAggregate(Guid.NewGuid());
        var evt1 = new TestDomainEvent("Event 1");
        var evt2 = new TestDomainEvent("Event 2");

        aggregate.EmitEvent(evt1);
        aggregate.EmitEvent(evt2);

        var drained = aggregate.DrainDomainEvents();
        drained.Should().HaveCount(2);
        aggregate.PendingDomainEventsCount.Should().Be(0);

        // Act: Requeue
        aggregate.RequeueDomainEvents(drained);

        // Assert: Events restored in order
        aggregate.PendingDomainEventsCount.Should().Be(2);
        aggregate.DomainEvents.Should().HaveCount(2);
        aggregate.DomainEvents[0].Should().BeSameAs(evt1);
        aggregate.DomainEvents[1].Should().BeSameAs(evt2);
    }

